"""type_marquee -- "Bookcloth Galley", the 5 x 6 marquee / numeric-field face.

All capitals, six rows tall, ink in columns 0..3 (column 4 is the letter gap,
the ellipsis being the one exception).  It is a letterpress proofing face at
the smallest size that can still carry serifs: the I and J wear slabs, the T
and Z hang little beaks from their arms, C G S E F L end in soft terminals.

Legend:  ``#`` slate ink   ``+`` ink-spread (a softer grey where the ink has
crept into the fibres -- terminals, beaks, brackets)   ``.`` paper.

The asterisk is drawn as a printer's dinkus lozenge, because the marquee uses
`` *** `` as its section break.
"""

from __future__ import annotations

GLYPHS: dict[str, tuple[str, ...]] = {}


def _g(ch: str, rows: str) -> None:
    r = tuple(x.ljust(5, ".") for x in rows.split())
    assert len(r) == 6 and all(len(x) == 5 for x in r), (ch, r)
    GLYPHS[ch] = r


_g("A", ".##. #..# #..# #### #..# #..#")
_g("B", "###. #..# ###. #..# #..# ###.")
_g("C", ".### #..+ #... #... #..+ .###")
