"""type_numerals -- "Bookcloth Clarendon", the 9 x 13 letterpress time figures.

Lining Clarendon numerals: two-pixel stems against one-pixel hairlines, ball
terminals on 2 3 5 6 9, a slab under the 1 and the 4, a beak on the 7.  The
figure stands on rows 1..11 of the cell, leaving a row of paper above and
below so the deboss lip under each stroke has somewhere to fall.

The 1 keeps its stem right of column 4 on purpose: the legacy ``numbers.bmp``
reserves row 6, columns 0..4 of the "1" cell as the *blank* minus strip.

Legend:  ``#`` slate ink   ``+`` ink-spread   ``.`` paper.
"""

from __future__ import annotations

DIGITS: dict[object, tuple[str, ...]] = {}


def _d(key, rows: str) -> None:
    r = tuple(rows.split())
    assert len(r) == 13 and all(len(x) == 9 for x in r), (key, [len(x) for x in r])
    DIGITS[key] = r


