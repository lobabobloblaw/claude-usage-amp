def glyphs() -> dict[str, tuple[int, tuple[str, ...]]]:
    return dict(_G)


def cell(ch: str):
    """Coverage array (CELL_H, CELL_W) for one character, ink starting at
    column 1 (a leading weak-ink column lands in column 0)."""
    import numpy as np
    out = np.zeros((CELL_H, CELL_W), dtype=np.float32)
    if ch == " " or ch not in _G:
        if ch != " ":
            return cell("?")
        return out
    top, rows = _G[ch]
    w = len(rows[0])
    first = min((i for i in range(w) if any(r[i] in "#+" for r in rows)), default=0)
    x0 = 1 - first
    for y, row in enumerate(rows):
        for x, k in enumerate(row):
            xx = x0 + x
            if k != "." and 0 <= xx < CELL_W:
                out[top + y, xx] = COVERAGE[k]
    return out


def measure(text: str, spacing: int = 1, space: int = 3) -> int:
    """Visual width of a string set with the SPEC 3.2 advance rule."""
    import numpy as np
    pen = 0
    last_gap = 0
    for ch in text:
        c = cell(ch)
        cols = np.nonzero((c >= 0.5).any(axis=0))[0]
        if cols.size == 0:
            pen += space
            last_gap = 0
        else:
            pen += int(cols[-1] - cols[0] + 1) + spacing
            last_gap = spacing
    return pen - last_gap
