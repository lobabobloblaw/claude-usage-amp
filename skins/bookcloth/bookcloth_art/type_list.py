"""type_list -- "Bookcloth Text", the Sessions-list typeface (plfont).

An old-style book face drawn for a 9 x 12 cell:

    row 0        clear
    row 1        ascender line   (b d f h k l stand taller than the capitals,
    row 2        capital line     as they do in Jenson and Garamond)
    row 4        x-height line   (a small x-height: 5 px)
    row 8        baseline
    rows 9..11   descenders      (a real, three-pixel descent for g j p q y)

Figures are **old-style**: 0 1 2 sit at the x-height, 6 and 8 ascend,
3 4 5 7 9 descend -- they are all five ink columns wide so a column of costs
still lines up on its decimal point.

Legend:  ``#`` full ink   ``+`` strong partial ink (thin strokes, serifs that
define the width)   ``:`` weak partial ink (bracket / ink-spread; never counts
as an ink column, so it lives in the letter-spacing)   ``.`` paper.
"""

from __future__ import annotations

CELL_W, CELL_H = 9, 12
BASELINE = 8
CAP_TOP = 2
X_TOP = 4
COVERAGE = {"#": 1.0, "+": 0.62, ":": 0.30, ".": 0.0}

_G: dict[str, tuple[int, tuple[str, ...]]] = {}


def G(ch: str, top: int, rows: str) -> None:
    r = tuple(rows.split())
    w = max(len(x) for x in r)
    r = tuple(x.ljust(w, ".") for x in r)          # ragged rows pad right
    assert all(set(x) <= set("#+:.") for x in r), (ch, r)
    assert top + len(r) <= CELL_H, ch
    _G[ch] = (top, r)


