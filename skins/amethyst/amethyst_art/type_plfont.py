def rows(ch: str) -> tuple[str, ...]:
    """The 8 dot rows (5 wide) of a character; unknown -> '?'."""
    r = _G.get(ch, _G["?"]).split("/")
    if len(r) == 7:
        r.append(".....")
    assert len(r) == 8 and all(len(x) == 5 for x in r), ch
    return tuple(r)


def chars():
    return list(_G)
