def ink_mask(ch: str) -> np.ndarray:
    """Bool (CELL_H, CELL_W) ink mask; ink starts at column 1."""
    start, rows = GLYPHS.get(ch, GLYPHS["?"])
    m = np.zeros((CELL_H, CELL_W), dtype=bool)
    if ch == " ":
        return m
    for j, row in enumerate(rows):
        for i, px in enumerate(row):
            if px == "#":
                m[start + j, 1 + i] = True
    return m


def coverage(ch: str, bloom: float = 1.0, raster: float = 0.12) -> np.ndarray:
    """Float coverage 0..1 for one cell: solid ink + phosphor halo."""
    m = ink_mask(ch).astype(np.float32)
    H, W = m.shape

    def sh(dx, dy):
        out = np.zeros_like(m)
        ys = slice(max(0, dy), H + min(0, dy))
        yd = slice(max(0, -dy), H + min(0, -dy))
        xs = slice(max(0, dx), W + min(0, dx))
        xd = slice(max(0, -dx), W + min(0, -dx))
        out[ys, xs] = m[yd, xd]
        return out

    halo = np.maximum.reduce([
        sh(1, 0) * 0.36,      # smear to the right (beam persistence)
        sh(0, 1) * 0.22,      # bloom below
        sh(1, 1) * 0.12,
        sh(-1, 0) * 0.10,
        sh(0, -1) * 0.07,
    ]) * bloom
    # two ink pixels either side of a gap pool their glow
    pool = (sh(1, 0) * sh(-1, 0)) * 0.12 * bloom
    halo = np.clip(halo + pool, 0, 0.46)
    ink = m.copy()
    # raster: odd rows of the cell are a touch dimmer, like a line-scanned tube
    ink[1::2, :] *= (1.0 - raster)
    return np.maximum(ink, halo * (1.0 - m))
