def draw(c, x: int, y: int, text: str, face: Face, col, a: float = 1.0,
         spacing: int | None = None, wear: float = 0.0, seed: int = 0) -> int:
    """Draw ``text``; ``wear`` (0..1) breaks the ink up like old stencil paint.
    Returns the x just past the text."""
    m = face.mask(text, spacing).astype(np.float32) * a
    if wear > 0:
        h, w = m.shape
        xs = np.arange(w, dtype=np.float32) + c.ox + x
        ys = np.arange(h, dtype=np.float32) + c.oy + y
        X, Y = np.meshgrid(xs, ys)
        n = M.fbm(X, Y, 0, seed + 71, octaves=2, sx=3.0, sy=2.2)
        g = M.grain(X, Y, seed + 72)
        k = np.clip((n * 0.7 + g * 0.3 - (0.62 - wear * 0.45)) * 4.0, 0, 1)
        m = m * (1.0 - k * 0.85)
    M.blend_mask(c, m, col, x, y)
    return x + m.shape[1]


def engraved(c, x: int, y: int, text: str, face: Face, col, a: float = 1.0, spacing=None,
             depth: float = 0.55, lip: float = 0.22):
    """Engraved and paint-filled: dark cut on the top/left of the strokes, a lit
    lip on the bottom/right, paint in the groove."""
    m = face.mask(text, spacing)
    h, w = m.shape
    pad = np.zeros((h + 2, w + 2), dtype=bool)
    pad[1:-1, 1:-1] = m
    sh = np.zeros_like(pad)
    sh[:-1, :-1] |= pad[1:, 1:]          # pixels up-left of ink
    sh &= ~pad
    lp = np.zeros_like(pad)
    lp[1:, 1:] |= pad[:-1, :-1]          # pixels down-right of ink
    lp &= ~pad
    lp &= ~sh
    M.blend_mask(c, sh.astype(np.float32) * depth, (5, 6, 8), x - 1, y - 1)
    M.blend_mask(c, lp.astype(np.float32) * lip, (223, 231, 234), x - 1, y - 1)
    M.blend_mask(c, m.astype(np.float32) * a, col, x, y)
    return x + w


def centred(c, cx: int, y: int, text: str, face: Face, col, **kw) -> int:
    w = face.width(text, kw.get("spacing"))
    x = int(cx - w // 2)
    draw(c, x, y, text, face, col, **kw)
    return x
