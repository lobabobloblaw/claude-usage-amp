class Face:
    def __init__(self, glyphs: dict, h: int, spacing: int = 1):
        self.h = h
        self.spacing = spacing
        self.rows = {k: _g(v) for k, v in glyphs.items()}
        for k, r in self.rows.items():
            assert len(r) == h and len({len(x) for x in r}) == 1, (k, r)

    def glyph(self, ch: str):
        if ch in self.rows:
            return self.rows[ch]
        u = ch.upper()
        return self.rows.get(u, self.rows[" "])

    def width(self, text: str, spacing: int | None = None) -> int:
        sp = self.spacing if spacing is None else spacing
        if not text:
            return 0
        return sum(len(self.glyph(ch)[0]) for ch in text) + sp * (len(text) - 1)

    def mask(self, text: str, spacing: int | None = None) -> np.ndarray:
        sp = self.spacing if spacing is None else spacing
        w = self.width(text, sp)
        m = np.zeros((self.h, max(1, w)), dtype=bool)
        x = 0
        for ch in text:
            g = self.glyph(ch)
            for j, row in enumerate(g):
                for i, px in enumerate(row):
                    if px == "#":
                        m[j, x + i] = True
            x += len(g[0]) + sp
        return m


