def cell_rows(ch: str) -> list[str]:
    """The glyph as CELL[1] rows of CELL[0] characters ('#' ink, '.' none)."""
    cw, chh = CELL
    spec = G.get(ch)
    rows = ["." * cw for _ in range(chh)]
    if spec is None:
        return rows
    top, body = int(spec[0]), spec[1:]
    for i, r in enumerate(body):
        y = top + i
        if 0 <= y < chh:
            rows[y] = ("." + r + "." * cw)[:cw]
    return rows
